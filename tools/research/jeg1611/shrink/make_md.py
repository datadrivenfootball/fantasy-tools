"""Render out/shrink/results.json as results.md (JEG-1611 steps 5-6)."""
from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "out" / "shrink"
R = json.loads((OUT / "results.json").read_text(encoding="utf-8"))
POS = ("RB", "WR", "TE")
L = []


def t(header, rows):
    L.append("| " + " | ".join(header) + " |")
    L.append("| " + " | ".join("---" for _ in header) + " |")
    for r in rows:
        L.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    L.append("")


def ci(v):
    return f"[{v[0]}, {v[1]}]"


L += ["# JEG-1611 steps 5-6: shrunk expected receptions (research)", "",
      "Generated by `tools/research/jeg1611/shrink/run_shrink.py` then `make_md.py`. Actuals only "
      "(nflverse weekly 2015-2025; 2024-2026 category totals for F). Leave-one-season-out CV over 11 seasons; "
      "decision weeks 5-10; truth = realized rest-of-season (week w to the last regular week) per game; "
      "players with >= 3 ROS games and >= 1 prior game. Hyperparameters (half-life in games, season decay, k) "
      "chosen on the 10 train seasons by MSE of ROS receptions per game.", "",
      f"Chosen form per position: {R['chosen_forms']} (role-aware prior kept where it beats the constant prior "
      "on pooled MSE and in >= 7 of 11 seasons).", ""]

L += ["## A-C: ROS receptions per game, out of sample", "",
      "MSE pooled over test rows; Spearman = mean within (season, week) of the position, 95% t-interval across 11 seasons. "
      "Seasons = test seasons with lower MSE than raw history (all prior games).", ""]
for p in POS:
    a = R["A_B_C"][p]
    L.append(f"**{p}** ({a['n_rows']} rows, {a['n_players']} players)")
    L.append("")
    rows = []
    for m, lab in (("pos_mean", "(i) position mean"), ("raw_all", "(ii) raw history, all prior games"),
                   ("raw_cur", "(iii) raw history, current season"), ("B", "B: EB, constant prior"),
                   ("C_linear", "C: EB, prior linear in history Std ppg"), ("C_bins", "C: EB, prior by Std ppg quintile")):
        v = a[m]
        rows.append([lab, v["mse"], v["rmse"], v["spearman"], ci(v["spearman_ci95"]) if v["spearman"] is not None else "",
                     v.get("seasons_beating_raw_all_mse", ""), v.get("seasons_beating_B_mse", "")])
    t(["model", "MSE", "RMSE", "Spearman", "95%", "seasons beat raw", "seasons beat B"], rows)
    L.append(f"C_linear - B MSE: {a['C_linear_minus_B_mse'][0]} {ci(a['C_linear_minus_B_mse'][1:])}; "
             f"mean shrinkage weight w: {a['mean_w']}.")
    L.append("")

L += ["## Fitted model (all 11 seasons; model.json)", ""]
rows = []
for p in POS:
    f = R["final_model"][p]
    for form in ("B", "C_linear", "ratio"):
        v = f[form]
        mark = " (chosen)" if form == f["chosen"] else (" (share model)" if form == "ratio" else "")
        rows.append([p, form + mark, v["half_life_games"] or "none", v["season_decay"], v["k"],
                     v["w_at_n_eff"]["6"], v["w_at_n_eff"]["17"], v["w_at_n_eff"]["34"],
                     v["n_eff_scenarios"]["6_current_games"]["w"], v["n_eff_scenarios"]["6_current_plus_1_prior_season"]["w"],
                     f"a={round(v['a'], 3)}, b={round(v['b'], 3)}" if v.get("a") is not None else round(v["mean"], 3)])
t(["pos", "form", "half-life (games)", "season decay", "k", "w at n_eff=6", "17", "34",
   "w: 6 cur games", "w: 6 cur + 1 prior season", "prior"], rows)
L += ["n_eff is the recency-weighted game count, so with a half-life of 8 games it saturates near 12: "
      "the estimator discounts old history mainly through recency, not through k. The share model's prior "
      "is on z = log(1 + rec/std).", ""]
L.append("CV-chosen parameters per held-out season are in results.json `cv_chosen_params`. They are stable: B picked "
         "half-life 8 games in all 33 position-folds (decay 0.5, 0.7 in 3 RB folds; k 2 RB, 1 WR/TE); C_linear picked "
         "k 2-3 for RB/WR in every fold.")
L.append("")

L += ["## D: within-position move, oracle vs model", "",
      "Oracle move = log((P_std + rec_ROS) / P_std) with realized ROS values; model move uses the model's rec_hat. "
      "All moves demeaned within (season, week, position). Slope = OLS of oracle on the move (slope < 1: the move "
      "overshoots the truth); 95% = season-block bootstrap (2000). `P_realized`: the same realized P_std in both moves "
      "(isolates the reception term, but P_std and rec_ROS share the future, see note). `P_forecast`: the move uses "
      "the recency-weighted history Std ppg as P_std (what a chart-anchored rebuild sees). `ratio_model` is the "
      "share model log(1 + share_hat), independent of P. Chart pool = top 36/36/18 per week by history PPR ppg.", ""]
for var in ("P_forecast", "P_realized"):
    L.append(f"**{var}**")
    L.append("")
    rows = []
    for pool in ("chart_top_n", "all_eligible"):
        for p in POS:
            r = R["D"][var][pool][p]
            for m in ("raw_all", "raw_cur", "model", "ratio_model"):
                v = r[m]
                rows.append([pool, p, r["n_rows"], m, v["slope"], ci(v["slope_ci95"]), v["spearman"],
                             ci(v["spearman_ci95"]), v["sd_within"], r["sd_oracle_within"]])
    t(["pool", "pos", "n", "move", "slope", "95%", "Spearman", "95%", "sd move", "sd oracle"], rows)

L += ["Note on `P_realized`: when a player's receptions fall short, his yards (and so his Standard points) fall too, "
      "so the realized ratio rec/P_std is much more stable than rec_hat/P_std. That is why even a calibrated "
      "rec/g estimate overshoots the ratio move (slope well below 1), and why the share should be modelled "
      "directly: the share model is calibrated (slope about 1 on all eligible) and ranks at least as well "
      "under `P_forecast`.", ""]

L += ["## E: mechanism test (predict ROS Standard within position)", ""]
labels = {"i_trailing_full": "(i) trailing Full ppg", "ii_trailing_std": "(ii) trailing Std ppg",
          "iii_full_minus_rec_hat": "(iii) trailing Full - rec_hat", "iv_ols_std_rec": "(iv) OLS on trailing std, rec",
          "v_ols_std_rec_rechat": "(v) OLS on trailing std, rec, rec_hat",
          "vi_full_forecast": "(vi) calibrated Full forecast (OLS, target ROS Full)",
          "vii_full_forecast_minus_rec_hat": "(vii) (vi) - rec_hat",
          "viii_full_forecast_over_share": "(viii) (vi) / (1 + share_hat)"}
for key, title in (("primary_ros_ppg_w5_10", "Primary: ROS Standard ppg, weeks 5-10, >= 3 ROS games"),
                   ("replication_M_ros_total_w5_8", "Replication of section M: ROS Standard total, weeks 5-8")):
    e = R["E"][key]
    L.append(f"**{title}** ({e['n_rows']} rows, {e['n_players']} players; pool = top 36/36/18 by trailing "
             "half-PPR, >= 2 current-season games)")
    L.append("")
    rows = []
    for m, lab in labels.items():
        v = e["methods"][m]
        rows.append([lab, v["spearman"], v.get("diff_vs_full", ""), ci(v["ci95"]) if "ci95" in v else "",
                     f"{v['seasons_beating_full']} of 11" if "seasons_beating_full" in v else "",
                     v.get("diff_vs_full_forecast", ""),
                     ci(v["ci95_vs_full_forecast"]) if "ci95_vs_full_forecast" in v else "",
                     f"{v['seasons_beating_full_forecast']} of 11" if "seasons_beating_full_forecast" in v else ""])
    t(["predictor", "Spearman", "diff vs (i)", "95%", "seasons won vs (i)", "diff vs (vi)", "95%", "seasons won vs (vi)"], rows)
    rows = []
    for p in POS:
        c = e["by_position"][p]["coef_iv_mean_over_folds"]
        rows.append([p, c["trailing_std"], c["trailing_rec"], c["rec_over_std_ratio"]] +
                    [e["by_position"][p][m] for m in ("i_trailing_full", "iii_full_minus_rec_hat", "vi_full_forecast",
                                                      "viii_full_forecast_over_share")])
    t(["pos", "(iv) coef trailing std", "(iv) coef trailing rec", "rec/std coef ratio", "Spearman (i)", "(iii)", "(vi)", "(viii)"], rows)

L += ["**What it means.** Shrinking the deduction does not rescue it: trailing Full minus rec_hat still loses to "
      "trailing Full in every season. The regression shows why: a trailing reception is worth more future Standard "
      "points than a trailing Standard point is (coefficient on trailing receptions about 0.3 per game for RB, "
      "0.7-0.8 for WR and TE, 2-3x the Standard coefficient for WR/TE), so receptions are usage, and a trailing rate "
      "with them removed is a worse forecast. That is a statement about trailing rates, not about converting a "
      "forecast. Once the anchor is a calibrated Full forecast (vi), the conversion no longer loses: subtracting "
      "rec_hat is neutral to slightly positive, and dividing by (1 + share_hat) from the share model wins in 11 of "
      "11 seasons (primary). So applying a reception deduction to a Full-anchored forecast is sound provided the "
      "anchor is a forecast that already prices usage (a chart is) and the deduction is the shrunk share, "
      "not raw history.", ""]

L += ["## F: stability of point shares, 2024-2026 category data", "",
      "Season totals per player (games >= 6, PPR ppg >= 5 rebuilt from categories, no 2-point conversions; "
      "2026 is weeks to date). Shares of PPR points: receptions, yards, TDs. Year-over-year Pearson and ICC(1) "
      "over players with >= 2 qualifying seasons.", ""]
rows = []
for p in POS:
    pr = R["F"]["pairs"][p]
    icc = R["F"]["icc"][p]
    for m in ("rec_share", "yds_share", "td_share", "rec_pg", "yds_pts_pg", "td_pts_pg", "targets_pg"):
        rows.append([p, m, pr["2024-2025"][m]["pearson"], pr["2025-2026"][m]["pearson"], icc[m]])
    rows.append([p, "n (pairs / ICC players)", pr["2024-2025"]["n"], pr["2025-2026"]["n"], icc["n_players"]])
t(["pos", "metric", "r 2024-25", "r 2025-26", "ICC"], rows)
L += ["Reception share is the most stable share for RB and WR (ICC 0.56 and 0.44 against 0.12-0.25 for TD and "
      "yards shares); for TE the three are similar and small (n = 41). Shares are compositional (they sum to about "
      "1), so the TD and yards shares absorb TD luck. This supports a player-specific term for receptions (RB, WR) "
      "but does not show TD/yard shares need none; it shows they are mostly noise year to year.", ""]

q = R["QB"]
L += ["## QB", "", f"ROS receptions per game mean {q['mean_rec_pg']} (99th pct {q['p99_rec_pg']}, max {q['max_rec_pg']}; "
      f"{q['share_rows_any_rec']} of rows have any), {q['rec_over_std']} of Standard points, n = {q['n_rows']}. "
      "Left alone (w = 0).", ""]

L += ["## Caveats", "",
      "- Hyperparameter leakage: train seasons after the test season use the test season's games as history "
      "features (not targets). Only 3 scalars per position are tuned, and the folds pick the same values.",
      "- 2015 decision points have no prior seasons in the file; histories start in 2015.",
      "- A week with no row is treated as not played (bye, injury, or no stat line).",
      "- MSE is unweighted across rows; ROS truth over 3+ games is itself noisy, which caps all Spearmans.",
      "- `P_forecast` uses the recency-weighted history Standard ppg as the denominator, noisier than a chart's "
      "value-implied points; the realistic slope for a chart sits between the two D variants.",
      "- F uses 2-3 seasons and 28-85 players per position; 2026 is partial.", ""]

(OUT / "results.md").write_text("\n".join(L), encoding="utf-8")
print("wrote", OUT / "results.md")
